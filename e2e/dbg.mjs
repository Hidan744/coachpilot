import { launch, fill, tap, see, registerWithTeam } from './lib.mjs';
const { browser, page } = await launch();
await registerWithTeam(page);
await tap(page, 'Библиотека');
await see(page, 'Светофор');
const dump = () => page.evaluate(() => [...document.querySelectorAll('input')].map(e => JSON.stringify(e.getAttribute('aria-label')) + '=' + e.value).join(' | '));
console.log('before:', await dump());
await fill(page, 'Поиск', 'рондо');
console.log('after:', await dump());
await page.waitForTimeout(1000);
console.log('after1s:', await dump());
await browser.close();
